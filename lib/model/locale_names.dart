/// `de_CH` → `German (Switzerland)`. Unknown parts are shown as they are.
String localeDisplayName(String locale) {
  final parts = locale.replaceAll('-', '_').split('_');
  final language = _languages[parts.first.toLowerCase()] ?? parts.first;
  final details = [
    for (final p in parts.skip(1))
      _scripts[p] ?? _regions[p.toUpperCase()] ?? p,
  ];
  return details.isEmpty ? language : '$language (${details.join(', ')})';
}
